def set_paragraph_text(p, text: str) -> None:
    """清空 runs 后写入纯文本，尽量保留段落样式。"""
    el = p._p
    for child in list(el):
        if child.tag == qn("w:r"):
            el.remove(child)
    run = p.add_run(text)


def paragraph_text(p) -> str:
    return "".join(t.text or "" for t in p._p.iter(qn("w:t")))


def main() -> None:
    if not SRC.exists():
        raise SystemExit(f"找不到文件: {SRC}")
    shutil.copy2(SRC, BACKUP)
    doc = Document(str(SRC))

    # 先处理段落
    to_delete = []
    for p in doc.paragraphs:
        raw = paragraph_text(p)
        key = raw.strip()
        if key in EXACT:
            new = EXACT[key]
            if new is None:
                to_delete.append(p)
            elif new != raw:
                set_paragraph_text(p, new)
            continue
        for prefix, replacement in PREFIX_REPLACEMENTS:
            if key.startswith(prefix) or raw.strip().startswith(prefix):
                set_paragraph_text(p, replacement)
                break
        else:
            # 去掉残留【】包裹（保守：仅当整格是【xxx】）
            if "【" in raw and "】" in raw:
                cleaned = raw
                # 常见残留
                for a, b in [
                    ("【", ""),
                    ("】", ""),
                ]:
                    cleaned = cleaned.replace(a, b)
                # 只在明显是占位清理时应用（避免误伤）
                if key.startswith("|") or key.startswith("###") or key.startswith(">"):
                    if cleaned != raw:
                        set_paragraph_text(p, cleaned)

    for p in to_delete:
        el = p._p
        parent = el.getparent()
        if parent is not None:
            parent.remove(el)

    # 再扫一遍表格（若有真表格）
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for p in cell.paragraphs:
                    raw = paragraph_text(p)
                    key = raw.strip()
                    if key in EXACT and EXACT[key] is not None:
                        set_paragraph_text(p, EXACT[key])

    doc.save(str(OUT))
    print(f"已备份: {BACKUP}")
    print(f"已写入: {OUT}")


if __name__ == "__main__":
    main()
